"use strict";
// The Gradle read half: the mask and block finder on both DSLs, and every id form the corpus uses.
const { test } = require("node:test");
const assert = require("node:assert");
const G = require("../scripts/writers/gradle.cjs");
const { createIO } = require("../scripts/lib/io.cjs");
const { materialize, fromFiles } = require("./helpers/project.cjs");

const read = (files) => G.read(createIO(fromFiles(files, { git: false })));
const ids = (facts) => Object.fromEntries(facts.flavors.map((f) => [f.name, f.effectiveId]));

const KTS = `plugins {
    id("com.android.application")
}
android {
    namespace = "com.acme.shop" // "android {" in a comment
    defaultConfig {
        applicationId = "com.acme.shop"
    }
    flavorDimensions += "env"
    productFlavors {
        create("dev") {
            dimension = "env"
            applicationId = "com.acme.shop.dev"
            resValue("string", "app_name", "Shop DEV")
        }
        create("production") {
            dimension = "env"
            applicationId = "com.acme.shop"
        }
    }
}
// productFlavors {
//     create("dev") { applicationId = "com.acme.old.dev" }
// }
`;

const GROOVY = `android {
    defaultConfig {
        applicationId "com.acme.shop"
    }
    flavorDimensions "default"
    productFlavors {
        dev {
            dimension "default"
            applicationIdSuffix ".dev"
        }
        production {
            dimension "default"
        }
    }
}
`;

test("the mask blanks comments and strings but keeps every offset", () => {
  const text = 'a // b {\nc "d { e" f /* g { */ h\n';
  const m = G.mask(text);
  assert.strictEqual(m.length, text.length);
  assert.ok(!m.includes("{"), "braces inside comments and strings are gone");
  assert.strictEqual(m.indexOf("h"), text.indexOf("h"));
  assert.ok(G.mask(text, { strings: false }).includes('"d { e"'), "strings survive when asked to");
});

test("the block finder returns the direct child, not a commented or nested look-alike", () => {
  const m = G.mask(KTS);
  const android = G.block(m, "android");
  assert.ok(android && KTS.slice(android.open, android.open + 1) === "{");
  const pf = G.block(m, "productFlavors", android);
  assert.ok(pf, "productFlavors is found inside android {}");
  assert.ok(KTS.slice(pf.open, pf.close).includes('create("dev")'));
  assert.strictEqual(G.block(m, "create", android), null, "a grandchild is not a child");
});

test("Kotlin explicit ids are read and the commented duplicate is invisible to them", () => {
  const f = read({ "android/app/build.gradle.kts": KTS });
  assert.strictEqual(f.dialect, "kts");
  assert.deepStrictEqual(ids(f), { dev: "com.acme.shop.dev", production: "com.acme.shop" });
  assert.deepStrictEqual(f.flavors[0].resValues.map((r) => [r.key, r.value]), [["app_name", "Shop DEV"]]);
  assert.strictEqual(f.owner, "hand");
  assert.ok(f.commentedDuplicate, "the commented block is reported as itself");
  assert.match(f.commentedDuplicate.at, /^android\/app\/build\.gradle\.kts:22$/);
});

test("Groovy suffix ids resolve against defaultConfig", () => {
  const f = read({ "android/app/build.gradle": GROOVY });
  assert.strictEqual(f.dialect, "groovy");
  assert.deepStrictEqual(ids(f), { dev: "com.acme.shop.dev", production: "com.acme.shop" });
  assert.strictEqual(f.flavors[0].suffix, ".dev");
});

test("flavors in an applied script are read, and flutter_flavorizr owns them", () => {
  const f = read({
    "android/app/build.gradle": `android {\n  defaultConfig { applicationId "com.acme.shop" }\n}\n// ----- BEGIN flavorDimensions (autogenerated by flutter_flavorizr) -----\napply from: "flavorizr.gradle"\n// ----- END flavorDimensions (autogenerated by flutter_flavorizr) -----\n`,
    "android/app/flavorizr.gradle": `android {\n  flavorDimensions += "flavor-type"\n  productFlavors {\n    dev {\n      applicationId "com.acme.shop.dev"\n      resValue "string", "app_name", "Shop Dev"\n    }\n    prod {\n      applicationId "com.acme.shop"\n    }\n  }\n}\n`,
  });
  assert.deepStrictEqual(ids(f), { dev: "com.acme.shop.dev", prod: "com.acme.shop" });
  assert.strictEqual(f.appliedFrom, "android/app/flavorizr.gradle");
  assert.strictEqual(f.owner, "flavorizr");
});

test("a computed default id is reported, never guessed", () => {
  const f = read({ "android/app/build.gradle": GROOVY.replace('applicationId "com.acme.shop"', "applicationId appConfigProperties.getProperty('APP_ID')") });
  assert.strictEqual(f.defaultId, null);
  assert.match(f.computedId.expr, /getProperty/);
  assert.deepStrictEqual(ids(f), { dev: null, production: null });
  assert.ok(f.flavors.every((x) => x.computed));
});

test("the wizard's legacy block is foreign, and its '#' re-run is a syntax error", () => {
  const legacy = KTS.replace('    flavorDimensions += "env"', '    // setup-flutter-envs: managed\n    flavorDimensions += "env"');
  assert.strictEqual(read({ "android/app/build.gradle.kts": legacy }).owner, "legacy");
  const rerun = `${legacy}# setup-flutter-envs: managed\nflavorDimensions += "env"\nproductFlavors {\n}\n`;
  const errors = read({ "android/app/build.gradle.kts": rerun }).errors.map((e) => e.why);
  assert.deepStrictEqual(errors, ["a line starts with '#', which Gradle does not accept", "a productFlavors block sits outside android {}"]);
});

test("the guard and the plugin are recognised by what they do", () => {
  const guarded = `${KTS}gradle.taskGraph.whenReady {\n    if (!file("src/dev/google-services.json").exists()) throw GradleException("missing")\n}\n`;
  const f = read({ "android/app/build.gradle.kts": guarded.replace('id("com.android.application")', 'id("com.android.application")\n    id("com.google.gms.google-services")') });
  assert.match(f.guardAt, /build\.gradle\.kts:\d+$/);
  assert.strictEqual(f.gmsApplied, true);
  const commentedOut = read({ "android/app/build.gradle.kts": `${KTS}// throw GradleException("google-services.json")\n` });
  assert.strictEqual(commentedOut.guardAt, null, "a guard in a comment guards nothing");
  assert.strictEqual(commentedOut.gmsApplied, false);
});

test("the pristine templates read as unflavored, with their AGP versions", () => {
  const p47 = G.read(createIO(materialize("pristine-flutter-3.47", undefined, { git: false })));
  assert.deepStrictEqual([p47.flavors.length, p47.defaultId.value, p47.agp, p47.owner], [0, "com.acme.shop", "9.1.0", "none"]);
  const p41 = G.read(createIO(materialize("pristine-flutter-3.41-pods", undefined, { git: false })));
  assert.deepStrictEqual([p41.flavors.length, p41.defaultId.value, p41.agp], [0, "com.acme.shop", "8.11.1"]);
});

// ---- the write half, read back through the read half ----

const { optree, twice } = require("./helpers/optree.cjs");
const { bundle } = require("./helpers/project.cjs");

const FLAVORS = [{ name: "dev", id: "com.acme.shop.dev" }, { name: "staging", id: "com.acme.shop.staging" }, { name: "production", id: "com.acme.shop" }];
const GROOVY_APP = `plugins {
    id "com.android.application"
    id "kotlin-android"
    id "dev.flutter.flutter-gradle-plugin"
}

android {
    namespace = "com.acme.shop"
    defaultConfig {
        applicationId = "com.example.shop"
        minSdk = 21
        targetSdk = flutter.targetSdkVersion
    }

    buildTypes {
        release {
            signingConfig = signingConfigs.debug
        }
    }
}

flutter {
    source = "../.."
}
`;
const GROOVY_SETTINGS = `pluginManagement {
    includeBuild("x")
}

plugins {
    id "dev.flutter.flutter-plugin-loader" version "1.0.0"
    id "com.android.application" version "8.1.0" apply false
    id "org.jetbrains.kotlin.android" version "1.8.22" apply false
}

include ":app"
`;
const readTree = (files) => G.read({ read: (rel) => (rel in files ? files[rel] : null) });

test("the flavors block goes right after defaultConfig {}, reads back with every id, and a re-run writes the same bytes", () => {
  const files = bundle("pristine-flutter-3.47");
  const [a, b] = twice(G.ops.flavors, { "android/app/build.gradle.kts": files["android/app/build.gradle.kts"] }, { flavors: FLAVORS });
  const text = a.text("android/app/build.gradle.kts");
  assert.strictEqual(b.text("android/app/build.gradle.kts"), text);
  assert.match(text, /versionName = flutter\.versionName\n {4}\}\n {4}\/\/ flutter-envs:begin flavors sha=[0-9a-f]{8}\n {4}flavorDimensions \+= "env"\n/);
  const facts = readTree(a.files());
  assert.strictEqual(facts.owner, "skill");
  assert.deepStrictEqual(Object.fromEntries(facts.flavors.map((f) => [f.name, f.effectiveId])), { dev: "com.acme.shop.dev", staging: "com.acme.shop.staging", production: "com.acme.shop" });
  assert.ok(facts.flavors.every((f) => f.dimension === "env"));
});

test("the Groovy flavors block uses Groovy syntax and reads back the same", () => {
  const t = optree({ "android/app/build.gradle": GROOVY_APP });
  G.ops.flavors(t.tree, { flavors: FLAVORS });
  const text = t.text("android/app/build.gradle");
  assert.match(text, /\n {4}flavorDimensions "env"\n {4}productFlavors \{\n {8}dev \{\n {12}dimension "env"\n {12}applicationId "com\.acme\.shop\.dev"\n/);
  assert.deepStrictEqual(readTree(t.files()).flavors.map((f) => f.effectiveId), FLAVORS.map((f) => f.id));
});

test("a flavors block edited by hand is a conflict and keeps its bytes", () => {
  const t = optree({ "android/app/build.gradle": GROOVY_APP });
  G.ops.flavors(t.tree, { flavors: FLAVORS });
  const edited = t.text("android/app/build.gradle").replace('applicationId "com.acme.shop.dev"', 'applicationId "com.acme.shop.develop"');
  const u = optree({ "android/app/build.gradle": edited });
  G.ops.flavors(u.tree, { flavors: FLAVORS });
  assert.match(u.conflicts.get("android/app/build.gradle"), /edited by hand/);
  assert.ok(!u.written.has("android/app/build.gradle"));
});

test("the placeholder default id and a low minSdk are set in place; flutter.minSdkVersion is left alone", () => {
  const t = optree({ "android/app/build.gradle": GROOVY_APP });
  G.ops["default-id"](t.tree, { id: "com.acme.shop" });
  G.ops["min-sdk"](t.tree, { min: 24 });
  const text = t.text("android/app/build.gradle");
  assert.match(text, /applicationId = "com\.acme\.shop"\n {8}minSdk = 24\n/);
  const facts = readTree(t.files());
  assert.deepStrictEqual([facts.defaultId.value, facts.minSdk], ["com.acme.shop", 24]);
  const kts = bundle("pristine-flutter-3.47")["android/app/build.gradle.kts"];
  const u = optree({ "android/app/build.gradle.kts": kts });
  G.ops["min-sdk"](u.tree, { min: 24 });
  assert.strictEqual(u.text("android/app/build.gradle.kts"), kts);
});

test("the guard block is appended in each dialect, recognised by the reader, and names the file and the CI variable", () => {
  for (const [file, text] of [["android/app/build.gradle.kts", bundle("pristine-flutter-3.47")["android/app/build.gradle.kts"]], ["android/app/build.gradle", GROOVY_APP]]) {
    const [a, b] = twice(G.ops.guard, { [file]: text }, { envs: ["dev", "staging", "production"] });
    const out = a.text(file);
    assert.strictEqual(b.text(file), out, `${file}: a re-run writes the same bytes`);
    assert.ok(out.startsWith(text), "the guard is appended");
    assert.match(out, /google-services\.json is missing\. /);
    assert.match(out, /GOOGLE_SERVICES_JSON_\$\{flavor\.(uppercase|toUpperCase)\(\)\}/);
    const facts = readTree(a.files());
    assert.ok(facts.guardAt && facts.managedGuard, `${file}: the reader sees the guard as the skill's`);
  }
});

test("the google-services plugin lines land after com.android.application in the app and the settings, once", () => {
  const files = { "android/app/build.gradle": GROOVY_APP, "android/settings.gradle": GROOVY_SETTINGS };
  const [a, b] = twice(G.ops["gms-plugin"], files, { version: "4.4.2" });
  assert.match(a.text("android/app/build.gradle"), /id "com\.android\.application"\n {4}id "com\.google\.gms\.google-services"\n {4}id "kotlin-android"/);
  assert.match(a.text("android/settings.gradle"), /id "com\.android\.application" version "8\.1\.0" apply false\n {4}id "com\.google\.gms\.google-services" version "4\.4\.2" apply false\n/);
  assert.deepStrictEqual(b.files(), a.files());
  assert.strictEqual(readTree(a.files()).gmsApplied, true);
  const p47 = bundle("pristine-flutter-3.47");
  const k = optree({ "android/app/build.gradle.kts": p47["android/app/build.gradle.kts"], "android/settings.gradle.kts": p47["android/settings.gradle.kts"] });
  G.ops["gms-plugin"](k.tree, { version: "4.4.2" });
  assert.match(k.text("android/settings.gradle.kts"), /id\("com\.google\.gms\.google-services"\) version "4\.4\.2" apply false/);
  const classpath = optree({ ...files, "android/build.gradle": 'buildscript {\n    dependencies {\n        classpath "com.google.gms:google-services:4.3.15"\n    }\n}\n' });
  G.ops["gms-plugin"](classpath.tree, { version: "4.4.2" });
  assert.strictEqual(classpath.text("android/settings.gradle"), GROOVY_SETTINGS, "a classpath declaration already pins a version, so settings gains none");
});
