"use strict";
// The failed wizard's six faults, each reproduced on a synthetic project, the structure that now catches it in a
// read-only check, and the apply-side halves: no build-time copy or generator is written, and a re-run adds nothing.
const { test } = require("node:test");
const assert = require("node:assert");
const M = require("../scripts/lib/managed.cjs");
const fs = require("node:fs");
const path = require("node:path");
const { run, checkProject, applyProject } = require("../scripts/envs.cjs");
const { verify } = require("../scripts/verify.cjs");
const { materialize } = require("./helpers/project.cjs");
const { SCHEMES, PBX, replace, drop } = require("./helpers/edit.cjs");

const codes = (ev) => [...Object.values(ev.criteria).flatMap((c) => c.findings), ...ev.repo];
const silent = { write: () => {} };

test("W1, it prompted for every value: a fresh app asks at most two questions", () => {
  const template = checkProject(materialize("pristine-flutter-3.47", (f) => {
    replace(f, "android/app/build.gradle.kts", 'applicationId = "com.acme.shop"', 'applicationId = "com.example.shop"');
    replace(f, PBX, "PRODUCT_BUNDLE_IDENTIFIER = com.acme.shop;", "PRODUCT_BUNDLE_IDENTIFIER = com.example.shop;", { all: true });
  }));
  assert.strictEqual(template.ctx.spec.questions.length, 2, "the template id and the environments");
  const named = checkProject(materialize("pristine-flutter-3.47"));
  assert.deepStrictEqual(named.ctx.spec.questions.map((q) => q.id), ["envs"], "a real production id is not asked");
});

test("W2, one iOS scheme: flavored configurations behind a single Runner scheme are a gap per environment", () => {
  const { ev } = checkProject(materialize("configured-flutter-3.47", (f) => {
    f[`${SCHEMES}/Runner.xcscheme`] = f[`${SCHEMES}/production.xcscheme`];
    for (const e of ["dev", "staging", "production"]) drop(f, `${SCHEMES}/${e}.xcscheme`);
  }));
  assert.deepStrictEqual(codes(ev).filter((f) => f.code === "ids.ios.scheme-missing").map((f) => f.env), ["dev", "staging", "production"]);
});

test("W3, icons copied at build time: environments with no static icons of their own show production's", () => {
  const { ev } = checkProject(materialize("configured-flutter-3.47", (f) => {
    for (const rel of Object.keys(f).filter((r) => /^android\/app\/src\/(dev|staging)\/res\/mipmap-/.test(r) || /AppIcon-(dev|staging)\.appiconset/.test(r))) delete f[rel];
    replace(f, PBX, /ASSETCATALOG_COMPILER_APPICON_NAME = "?AppIcon-(dev|staging)"?;/g, "ASSETCATALOG_COMPILER_APPICON_NAME = AppIcon;");
    f["assets/icons/dev/ic_launcher.png"] = f["android/app/src/main/res/mipmap-mdpi/ic_launcher.png"];
    f.Makefile += "icons:\n\tbash scripts/set-env-icons.sh $(env)\n";
  }));
  const same = codes(ev).filter((f) => f.code === "identity.icon-same");
  assert.deepStrictEqual(same.map((f) => f.env).sort(), ["dev", "dev", "staging", "staging"], "both platforms, both non-production environments");
});

test("W4, firebase_options generated from the env file: literal options for every environment are a gap", () => {
  const { ev } = checkProject(materialize("configured-flutter-3.47", (f) => {
    f["lib/firebase_options.dart"] = "// File generated by FlutterFire CLI.\nimport 'package:firebase_core/firebase_core.dart';\n\nclass DefaultFirebaseOptions {\n  static const FirebaseOptions currentPlatform = FirebaseOptions(\n    apiKey: 'AIza-FAKE-GENERATED',\n    appId: '1:100000000001:android:gen',\n    messagingSenderId: '100000000001',\n    projectId: 'acme-dev-staging',\n  );\n}\n";
    f.Makefile += "firebase-options:\n\tbash scripts/generate-firebase-options.sh $(env)\n";
  }));
  assert.ok(codes(ev).some((f) => f.code === "firebase.options-not-env"));
});

test("W5, a marker written with // and checked with #: one function writes and reads it, and the wizard's double block is caught", () => {
  for (const syntax of Object.keys(M.SYNTAX)) {
    const { text } = M.ensureBlock("android {\n}\n", { id: "flavors", syntax, body: "x\n", anchor: (t) => t.length });
    assert.ok(M.readBlock(text, { id: "flavors", syntax }), `${syntax} reads back what it wrote`);
    assert.deepStrictEqual(Object.keys(M.SYNTAX).filter((s) => s !== syntax && M.readBlock(text, { id: "flavors", syntax: s })), [], "no other syntax claims it");
  }
  const { ev } = checkProject(materialize("configured-flutter-3.47", (f) => {
    replace(f, "android/app/build.gradle.kts", /    \/\/ flutter-envs:begin flavors sha=[0-9a-f]{8}\n/, "    // setup-flutter-envs: managed\n");
    replace(f, "android/app/build.gradle.kts", "    // flutter-envs:end flavors\n", "");
    replace(f, "android/app/build.gradle.kts", "\nkotlin {", '\n    # setup-flutter-envs: managed\n    flavorDimensions += "env"\n    productFlavors {\n        create("dev") { applicationId = "com.acme.shop.dev" }\n    }\n\nkotlin {');
  }));
  const found = codes(ev).map((f) => f.code);
  assert.ok(found.includes("ids.android.foreign-block"), "the legacy block is foreign, never duplicated");
  assert.strictEqual(found.filter((c) => c === "repo.unreadable-file").length, 2, "the '#' line and the stray productFlavors both break the Gradle file");
});

// Every text file apply wrote, for scanning; the badged icons themselves are binary.
const written = (dir, receipt) => receipt.changes.filter((c) => c.state === "created" || c.state === "updated").map((c) => [c.file, fs.readFileSync(path.join(dir, c.file))]).filter(([, b]) => !b.includes(0)).map(([f, b]) => [f, b.toString("utf8")]);

test("W3 and W4 after apply: nothing copies icons at build time, and no generator script lands in the project", () => {
  const dir = materialize("pristine-flutter-3.47");
  const r = applyProject(dir, { sets: ["prodId=com.acme.shop"], now: "20261021T000000Z" });
  assert.strictEqual(r.code, 0);
  assert.ok(r.receipt.changes.some((c) => c.file.endsWith("AppIcon-dev.appiconset/Icon-App-1024x1024@1x.png") && c.state === "created"), "the icons are static files in the project");
  for (const [file, text] of written(dir, r.receipt)) assert.ok(!/assets\/icons/.test(text), `${file} references assets/icons`);
  const phases = checkProject(dir).ctx.facts.pbxproj.targets.flatMap((t) => t.phases).filter((p) => p.script);
  assert.ok(phases.length > 0, "the Runner phases were read");
  assert.deepStrictEqual(phases.filter((p) => /\.png\b/i.test(p.script)).map((p) => p.name), [], "no build phase references a PNG");
  assert.deepStrictEqual(r.receipt.changes.filter((c) => c.file.startsWith("scripts/")).map((c) => c.file), [], "apply creates nothing under scripts/");
});

test("W5 after apply: on the wizard's legacy block, apply adds no second flavor block, and a second apply adds nothing", () => {
  const dir = materialize("configured-flutter-3.47", (f) => {
    replace(f, "android/app/build.gradle.kts", /    \/\/ flutter-envs:begin flavors sha=[0-9a-f]{8}\n/, "    // setup-flutter-envs: managed\n");
    replace(f, "android/app/build.gradle.kts", "    // flutter-envs:end flavors\n", "");
  });
  const first = applyProject(dir, { now: "20261021T000000Z" });
  const gradle = fs.readFileSync(path.join(dir, "android/app/build.gradle.kts"), "utf8");
  assert.strictEqual((gradle.match(/productFlavors\s*\{/g) || []).length, 1, "one flavor block, the wizard's");
  assert.ok(!/flutter-envs:begin flavors/.test(gradle), "apply did not add its own beside the foreign one");
  const second = applyProject(dir, { now: "20261021T000000Z" });
  assert.deepStrictEqual(second.receipt.changes.filter((c) => c.state !== "unchanged").map((c) => c.file), []);
  assert.strictEqual(first.code, 0);
});

test("W6, acceptance never run on a build: with no tool on PATH, verify reports not-run with a reason, never pass", () => {
  const { ctx, ev } = checkProject(materialize("configured-flutter-3.47"));
  const result = verify(ctx, ev, { tier: "config", tool: () => null, run: () => { throw new Error("no tool may run"); } });
  const config = result.checks.filter((c) => c.tier === "config");
  assert.ok(config.length >= 4, "the config checks are all reported");
  for (const c of config) {
    assert.strictEqual(c.result, "not-run", c.id);
    assert.ok(c.why && c.why.length > 10, `${c.id} says why`);
  }
  const err = [];
  assert.strictEqual(run(["firebase", "--app", materialize("configured-flutter-3.47")], { stdout: silent, stderr: { write: (s) => err.push(s) } }), 2, "the firebase verb runs nothing without --plan or --confirm");
  assert.match(err.join(""), /--plan/);
});
